import { useEffect, useRef, useState } from 'react'
import type { Bookmark } from '@shared/contracts/bookmarks'
import type { Chapter } from '@shared/contracts/player'
import { formatTime } from './format-time'

/** The chapter playing at `seconds`, if the file has chapters. */
export function chapterAt(chapters: readonly Chapter[], seconds: number): Chapter | null {
  let found: Chapter | null = null
  for (const chapter of chapters) {
    if (chapter.time <= seconds) found = chapter
    else break
  }
  return found
}

const PREVIEW_DELAY_MS = 60

interface TimelineProps {
  duration: number | null
  position: number | null
  chapters: readonly Chapter[]
  bookmarks: readonly Bookmark[]
  onSeek: (seconds: number) => void
}

/**
 * Seek bar with chapter and bookmark markers. Hovering shows the time, chapter, and a preview
 * frame generated by the main process (requests are throttled; stale ones resolve to null).
 */
export function Timeline({ duration, position, chapters, bookmarks, onSeek }: TimelineProps) {
  const [hover, setHover] = useState<{ seconds: number; x: number; width: number } | null>(null)
  const [preview, setPreview] = useState<{ seconds: number; url: string } | null>(null)
  const latest = useRef(0)
  const total = duration ?? 0
  const hoverSeconds = hover?.seconds ?? null

  useEffect(() => {
    if (hoverSeconds === null || total <= 0) return
    const request = ++latest.current
    const timer = window.setTimeout(() => {
      window.frame.player
        .previewAt(hoverSeconds)
        .then((url) => {
          if (url && request === latest.current) setPreview({ seconds: hoverSeconds, url })
        })
        .catch(() => undefined)
    }, PREVIEW_DELAY_MS)
    return () => window.clearTimeout(timer)
  }, [hoverSeconds, total])

  const percent = (seconds: number) => `${Math.min(100, (seconds / total) * 100)}%`
  const chapter = hover ? chapterAt(chapters, hover.seconds) : null

  return (
    <div
      className="relative"
      onPointerMove={(e) => {
        if (total <= 0) return
        const rect = e.currentTarget.getBoundingClientRect()
        const x = Math.min(rect.width, Math.max(0, e.clientX - rect.left))
        setHover({ seconds: (x / rect.width) * total, x, width: rect.width })
      }}
      onPointerLeave={() => {
        latest.current++
        setHover(null)
        setPreview(null)
      }}
    >
      {hover && (
        <div
          data-testid="timeline-hover"
          className="pointer-events-none absolute bottom-full mb-2 flex -translate-x-1/2 flex-col items-center gap-1"
          style={{ left: Math.min(hover.width - 70, Math.max(70, hover.x)) }}
        >
          {preview && (
            <img
              src={preview.url}
              alt=""
              data-testid="timeline-preview"
              className="w-[140px] rounded border border-border bg-bg"
            />
          )}
          <div className="rounded bg-bg/95 px-2 py-0.5 text-center text-xs tabular-nums shadow">
            {chapter?.title && <div className="max-w-48 truncate text-muted">{chapter.title}</div>}
            {formatTime(hover.seconds)}
          </div>
        </div>
      )}
      <input
        type="range"
        aria-label="Seek"
        min={0}
        max={total}
        step={0.1}
        value={Math.min(position ?? 0, total)}
        disabled={total <= 0}
        onChange={(e) => onSeek(Number(e.currentTarget.value))}
        className="w-full accent-[var(--frame-accent)]"
      />
      {total > 0 && (
        <div className="pointer-events-none absolute inset-x-0 top-0 h-1.5" aria-hidden="true">
          {chapters
            .filter((c) => c.time > 0)
            .map((c) => (
              <span
                key={`c${c.time}`}
                data-testid="chapter-marker"
                className="absolute top-0 h-1.5 w-0.5 -translate-x-1/2 bg-muted/80"
                style={{ left: percent(c.time) }}
              />
            ))}
          {bookmarks.map((b) => (
            <span
              key={`b${b.id}`}
              data-testid="bookmark-marker"
              className="absolute top-0 h-1.5 w-1 -translate-x-1/2 rounded-sm bg-accent"
              style={{ left: percent(b.position) }}
            />
          ))}
        </div>
      )}
    </div>
  )
}
