/** Normalizes a language tag or name to a Frame code, or null if unknown. */
export function normalizeLanguage(value: string | null | undefined): string | null {
  if (!value) return null
  const key = value.trim().toLowerCase().replace(/_/g, '-')
  if (byCode.has(key)) return byCode.get(key)?.code ?? null
  if (ALIASES[key]) return ALIASES[key] ?? null
  const base = key.split('-')[0] ?? ''
  if (byCode.has(base)) return byCode.get(base)?.code ?? null
  return ALIASES[base] ?? null
}

export function languageLabel(code: string | null): string {
  if (!code) return 'Unknown language'
  return byCode.get(code.toLowerCase())?.name ?? code
}
